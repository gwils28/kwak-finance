/** 1 -> "st", 2 -> "nd", 3 -> "rd", 11 -> "th", 21 -> "st". */
function ordinal(day: number): string {
  const suffix = { one: "st", two: "nd", few: "rd", other: "th" } as Record<string, string>;
  return suffix[new Intl.PluralRules("en", { type: "ordinal" }).select(day)] ?? "th";
}

